"use client";

import { KeyRound, Loader2 } from "lucide-react";
import { useState } from "react";
import {
  CopyButton,
  Segmented,
  ToolField,
  ToolOptions,
  ToolOutput,
  ToolPanes,
} from "~/components/tools/tool-io";
import { Button } from "~/components/ui/button";
import { generateRsaKeyPair, type KeyPairPem } from "~/utils/rsa";

const SIZES = [
  { value: "2048" as const, label: "2048" },
  { value: "3072" as const, label: "3072" },
  { value: "4096" as const, label: "4096" },
];

export function RsaKeypairTool() {
  const [size, setSize] = useState("2048");
  const [pair, setPair] = useState<KeyPairPem | null>(null);
  const [working, setWorking] = useState(false);

  const generate = async () => {
    setWorking(true);
    try {
      setPair(await generateRsaKeyPair(Number(size) as 2048 | 3072 | 4096));
    } finally {
      setWorking(false);
    }
  };

  return (
    <div className="flex flex-col gap-5">
      <ToolOptions>
        <Segmented
          label="Key size"
          value={size}
          options={SIZES}
          onChange={setSize}
        />
        <Button type="button" onClick={generate} disabled={working}>
          {working ? <Loader2 className="animate-spin" /> : <KeyRound />}
          {working ? "Generating" : "Generate keypair"}
        </Button>
      </ToolOptions>

      <ToolPanes>
        <ToolField
          label="Public key"
          action={<CopyButton value={pair?.publicKey ?? ""} />}
        >
          <ToolOutput
            value={pair?.publicKey ?? ""}
            placeholder="Generate a pair to see the public key."
            className="min-h-64 text-xs"
          />
        </ToolField>
        <ToolField
          label="Private key"
          action={<CopyButton value={pair?.privateKey ?? ""} />}
        >
          <ToolOutput
            value={pair?.privateKey ?? ""}
            placeholder="Generate a pair to see the private key."
            className="min-h-64 text-xs"
          />
        </ToolField>
      </ToolPanes>

      <p className="text-sm leading-relaxed text-muted-foreground">
        The pair is generated by your browser with Web Crypto and exported as
        PEM. The private key is never transmitted, and 4096 bits can take a few
        seconds.
      </p>
    </div>
  );
}
