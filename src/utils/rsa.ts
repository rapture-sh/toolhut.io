import { toBase64, wrapLines } from "~/utils/bytes";

export const RSA_SIZES = [2048, 3072, 4096] as const;

export type RsaSize = (typeof RSA_SIZES)[number];

export interface KeyPairPem {
  publicKey: string;
  privateKey: string;
}

/** Injected so the tests can use Node's implementation. */
export type KeySubtle = Pick<SubtleCrypto, "generateKey" | "exportKey">;

const platformSubtle = (): KeySubtle => crypto.subtle;

export function toPem(label: string, der: ArrayBuffer): string {
  const body = wrapLines(toBase64(new Uint8Array(der)));
  return `-----BEGIN ${label}-----\n${body}\n-----END ${label}-----`;
}

/**
 * An RSASSA-PKCS1-v1_5 pair, exported as SPKI and PKCS8 PEM. Generated by the
 * browser, so the private key never exists anywhere else.
 */
export async function generateRsaKeyPair(
  size: RsaSize,
  subtle: KeySubtle = platformSubtle(),
): Promise<KeyPairPem> {
  const pair = (await subtle.generateKey(
    {
      name: "RSASSA-PKCS1-v1_5",
      modulusLength: size,
      publicExponent: new Uint8Array([1, 0, 1]),
      hash: "SHA-256",
    },
    true,
    ["sign", "verify"],
  )) as CryptoKeyPair;

  const [spki, pkcs8] = await Promise.all([
    subtle.exportKey("spki", pair.publicKey),
    subtle.exportKey("pkcs8", pair.privateKey),
  ]);

  return {
    publicKey: toPem("PUBLIC KEY", spki),
    privateKey: toPem("PRIVATE KEY", pkcs8),
  };
}
